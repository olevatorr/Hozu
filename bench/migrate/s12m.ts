// Dry run of trial 0021's s12m (ADR 0043 Measure) on scratch copies: node bench/migrate/s12m.ts [out.md]
import { execFileSync, spawnSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
const bin = join(root, 'packages/cli/bin/hozu.js')
const modules08 = join(root, 'examples/notes/node_modules')
const out = process.argv[2] ?? join(root, 'bench/migrate/s12m.md')
const scratch = mkdtempSync(join(tmpdir(), 'hozu-s12m-'))

const hozu = (args: string[], cwd: string) => {
  const r = spawnSync(process.execPath, [bin, ...args], { cwd, maxBuffer: 1 << 26 })
  return { code: r.status ?? 1, text: `${r.stdout}${r.stderr}`.trimEnd() }
}

function shim(from: string, to: string) {
  mkdirSync(to, { recursive: true })
  for (const e of readdirSync(from)) if (e !== '.cache') symlinkSync(join(from, e), join(to, e))
}

const fence = (text: string) => `\`\`\`\n${text}\n\`\`\``
const sections: string[] = [
  '# s12m dry run (trial 0021, ADR 0043 Measure)',
  '',
  `Generated by \`node bench/migrate/s12m.ts\` on scratch copies of tag \`s12\`; the trial apps are neither changed nor tagged.`,
  'Per run: (1) `hozu migrate 0.8` with the app’s installed 0.7 packages, (2) the same after linking the 0.8',
  'workspace packages, (3) an explicit `hozu check --update-lock` in the scratch copy, (4) `hozu check`.',
]
for (const run of ['hozu-run1', 'hozu-run2']) {
  const app = join(homedir(), 'hozu-trial-0020', run, 'app')
  if (!existsSync(join(app, '.git'))) {
    sections.push('', `## ${run}`, '', `skipped: ${app} does not exist`)
    continue
  }
  const dir = join(scratch, run)
  mkdirSync(dir)
  execFileSync('sh', ['-c', `git -C "${app}" archive s12 | tar -x -C "${dir}"`])
  shim(join(app, 'node_modules'), join(dir, 'node_modules'))
  const lock = readFileSync(join(dir, 'hozu.lock.json'), 'utf8')
  const first = hozu(['migrate', '0.8'], dir)
  for (const m of ['@hozu', 'zod']) {
    rmSync(join(dir, 'node_modules', m))
    symlinkSync(join(modules08, m), join(dir, 'node_modules', m))
  }
  const second = hozu(['migrate', '0.8'], dir)
  const unchanged = readFileSync(join(dir, 'hozu.lock.json'), 'utf8') === lock
  const accept = hozu(['check', '--update-lock'], dir)
  const check = hozu(['check'], dir)
  sections.push(
    '',
    `## ${run}`,
    '',
    `### 1. \`hozu migrate 0.8\` on 0.7 (exit ${first.code})`,
    '',
    fence(first.text),
    '',
    `### 2. \`hozu migrate 0.8\` after the upgrade (exit ${second.code})`,
    '',
    `hozu.lock.json unchanged by both runs: ${unchanged ? 'yes' : 'NO'}`,
    '',
    fence(second.text),
    '',
    `### 3. \`hozu check --update-lock\` (exit ${accept.code})`,
    '',
    fence(accept.text.split('\n').slice(-1)[0] ?? ''),
    '',
    `### 4. \`hozu check\` (exit ${check.code})`,
    '',
    fence(check.text),
  )
}
writeFileSync(out, `${sections.join('\n')}\n`)
rmSync(scratch, { recursive: true, force: true })
console.log(`wrote ${out}`)
