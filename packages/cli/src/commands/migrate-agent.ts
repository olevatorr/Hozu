const KNOWN = [GUIDE_07, GUIDE_07.replace(BROWSE, '')]

const fill = (text: string, values: Record<string, string>) =>
  Object.entries(values).reduce((out, [key, value]) => out.replaceAll(`__${key}__`, value), text)

function filled(template: string, target: (typeof TARGETS)[number], name: string, runner: Runner) {
  const note =
    runner === 'pnpm exec'
      ? ''
      : `\nThe skill writes commands as \`pnpm exec …\`; in this app use \`${runner} …\`.\n`
  return fill(fill(template, { READ: target.read }), {
    NAME: name,
    RUN: runner,
    SKILL: target.skill,
    NOTE: note,
  })
}

export function currentGuide(): string {
  const require = createRequire(import.meta.url)
  return readFileSync(join(dirname(require.resolve('create-hozu')), '../templates/guide.md'), 'utf8')
}

export type BlockResult =
  | { kind: 'replaced' | 'marked' | 'written' | 'current'; code: string }
  | { kind: 'custom'; block: string }

/** The new Hozu block of a CLAUDE.md / AGENTS.md: between markers, or the whole file when it is a known template. */
export function migrateGuide(
  existing: string | null,
  target: (typeof TARGETS)[number],
  dir: string,
  runner: Runner,
  template = currentGuide(),
): BlockResult {
  const name = existing?.match(/^# (.+)$/m)?.[1] ?? basename(dir)
  const detected = RUNNERS.find((r) => existing?.includes(`${r} hozu check`)) ?? runner
  const block = `${BEGIN}\n${filled(template, target, name, detected).trimEnd()}\n${END}\n`
  if (existing === null) return { kind: 'written', code: block }
  const begin = existing.indexOf(BEGIN)
  const end = existing.indexOf(END)
  if (begin >= 0 && end > begin) {
    const code = existing.slice(0, begin) + block + existing.slice(end + END.length).replace(/^\n/, '')
    return { kind: code === existing ? 'current' : 'replaced', code }
  }
  for (const known of [...KNOWN, template])
    for (const r of RUNNERS)
      if (existing === filled(known, target, name, r)) return { kind: 'marked', code: block }
  return { kind: 'custom', block }
}

export const skillTargets = (dir: string) => TARGETS.filter((t) => existsSync(join(dir, t.skill)))
