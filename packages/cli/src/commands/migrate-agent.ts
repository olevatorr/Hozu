import { existsSync, readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { basename, dirname, join } from 'node:path'

export const BEGIN = '<!-- hozu: generated by hozu skill; edits between these markers are replaced -->'
export const END = '<!-- /hozu -->'

const RUNNERS = ['pnpm exec', 'npx', 'yarn', 'bunx'] as const
type Runner = (typeof RUNNERS)[number]

export const TARGETS = [
  { guide: 'CLAUDE.md', skill: '.claude/skills/hozu', read: 'Use the `hozu` skill (`__SKILL__/SKILL.md`).' },
  {
    guide: 'AGENTS.md',
    skill: '.agents/skills/hozu',
    read: 'Read `__SKILL__/SKILL.md` before writing or changing any Hozu code.',
  },
] as const

const BROWSE =
  "__RUN__ hozu browse / --do 'click Save'     # real browser, no server: errors, widgets, text after steps\n"

