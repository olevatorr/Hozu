export type MessageKey = keyof typeof en

export interface MessagesFile {
  hozu: string
  messages: Record<string, string>
}

let current: Record<string, string> = {}

export const setMessages = (messages: Record<string, string>): void => {
  current = messages
}

/** One DevTools string in the person's language (ADR 0060 D): their file's text, else English. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const text = current[key] ?? (en as Record<string, string>)[key] ?? key
  return vars
    ? text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all))
    : text
}

const placeholders = (text: string) => [...text.matchAll(/\{(\w+)\}/g)].map((m) => m[1]!).sort()

/** What a translation lacks (shown in English), what it names that DevTools no longer has, and wrong placeholders. */
export function checkMessages(messages: Record<string, string>): {
  missing: string[]
  unknown: string[]
  placeholders: string[]
} {
  const base = en as Record<string, string>
  return {
    missing: Object.keys(base).filter((k) => !(k in messages)),
    unknown: Object.keys(messages).filter((k) => !(k in base)),
    placeholders: Object.keys(messages).filter(
      (k) => k in base && placeholders(messages[k]!).join() !== placeholders(base[k]!).join(),
    ),
  }
}

/** The messages of a file in the `hozu devtools messages` shape, or of a plain key → text object. */
export function messagesOf(json: unknown): Record<string, string> {
  const inner =
    json && typeof json === 'object' && 'messages' in json ? (json as { messages: unknown }).messages : json
  if (!inner || typeof inner !== 'object' || Array.isArray(inner)) return {}
  return Object.fromEntries(
    Object.entries(inner).filter((e): e is [string, string] => typeof e[1] === 'string'),
  )
}
